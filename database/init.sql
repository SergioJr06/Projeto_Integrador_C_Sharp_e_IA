CREATE TABLE IF NOT EXISTS infracoes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  camera_id text NOT NULL,
  epis_faltantes text NOT NULL,
  nivel_confianca numeric NOT NULL CHECK (nivel_confianca >= 0 AND nivel_confianca <= 1),
  caminho_evidencia text NOT NULL,
  data_hora timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_infracoes_data_hora ON infracoes (data_hora DESC);
